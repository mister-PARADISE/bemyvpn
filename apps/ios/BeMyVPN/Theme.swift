import SwiftUI

/// Палитра — та же, что в Android-приложении (тёмная тема).
enum Theme {
    // ── ЛЕСТНИЦА ПОВЕРХНОСТЕЙ: ЧЕТЫРЕ СТУПЕНИ, А НЕ ОДИННАДЦАТЬ ──
    //
    // Замер по снимкам давал одиннадцать разных подложек, и порядок в них был
    // нарушен: парящая панель оказывалась ТЕМНЕЕ карточки под ней — оттого и не
    // парила. Ступеней теперь ровно четыре, и каждая значит одно:
    // ЦВЕТНОСТЬ, А НЕ СЕРОСТЬ. Ступени были почти нейтрально-серыми
    // (насыщенность 26–30% при фоне в 29%), и рядом с фоном читались как грязь:
    // у страницы синева есть, у карточек — нет. Насыщенность поднята до 39–45%
    // при ТОЙ ЖЕ светлоте: контраст подписей зависит только от яркости, поэтому
    // цветность можно добавлять даром. Тон оставлен фоновый (220°).
    //
    // ШАГИ РАЗВЕДЕНЫ. Между s2 и float было 0.99 по CIE L* — глаз такой ступени
    // не видит, обе поверхности выглядели «никак». Теперь 3.0 / 2.5 / 2.4.
    // Потолок держит подпись: dim на плитке = 5.37 (было 5.34, ниже нельзя).
    static let bg      = Color(hex: 0x0B0E14)   // s0 — страница                          L* 3.9
    static let card    = Color(hex: 0x121C2F)   // s1 — карточка списка, поле, «поделиться» L* 10.3
    static let cardHi  = Color(hex: 0x172238)   // s2 — раскрытая карточка, выбранное, чип  L* 13.3
    static let tile    = Color(hex: 0x1F2C47)   // s3 — плитка внутри панели/карточки       L* 18.1
    static let accent  = Color(hex: 0x7BA6F0)
    static let fg      = Color(hex: 0xEAECEF)
    static let dim     = Color(hex: 0x99A1B4)
    static let green   = Color(hex: 0x34E29E)
    static let red     = Color(hex: 0xF2707E)
    static let amber   = Color(hex: 0xF5B14C)
}

extension Color {
    init(hex: UInt32) {
        self.init(
            .sRGB,
            red:   Double((hex >> 16) & 0xFF) / 255,
            green: Double((hex >> 8) & 0xFF) / 255,
            blue:  Double(hex & 0xFF) / 255,
            opacity: 1
        )
    }
}
