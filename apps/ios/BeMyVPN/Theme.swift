import SwiftUI
import UIKit

/// Палитра приложения (тёмная тема).
///
/// ЦВЕТА И ДОЛИ СЮДА НЕ ПИШУТ РУКАМИ. Они живут в `design/palette.toml` и
/// раскладываются отсюда и по трём другим темам скриптом `design/sync-palette.py`
/// — см. размеченный участок ниже. Правка мимо источника продержится до первого
/// прогона сторожа (`apps/bmv-gui/tests/palette_is_one_source.rs`).
///
/// Всё, что ВНЕ участка, написано руками: пояснения и смешение цветов. Их скрипт
/// не трогает.
enum Theme {
    // ── ЛЕСТНИЦА ПОВЕРХНОСТЕЙ: ПЯТЬ СТУПЕНЕЙ, ФОН НЕЙТРАЛЬНЫЙ ──
    //
    // УГОЛЬ ВМЕСТО СИНЕВЫ. Прежний фон был синим (тон 220°), и синеву несла вся
    // лестница. Сам по себе фон нравился, но блоки НА нём выглядели грязными:
    // цветная поверхность поверх цветной — это два близких оттенка, а два
    // близких оттенка глаз читает не как ступень, а как пятно. Тон убран
    // целиком: у угля нет оттенка, спорить не с чем, и ступень видно как
    // ступень. Цвет остаётся ровно там, где он что-то значит — в акценте,
    // янтаре и красном.
    //
    // ШАГИ ИДУТ ПО ПОРЯДКУ: 5.7 / 3.5 / 2.4 / 5.3 по CIE L*, перепад блока к
    // фону — 5.7 / 9.2 / 11.5 / 16.9. Парящее (floatSurface в ContentView)
    // НАМЕРЕННО между s2 и s3: выше карточек списка, но ниже плиток, лежащих
    // внутри него.
    //
    // ШАГИ НАМЕРЕННО НЕРАВНЫЕ, И ЗАПАС РОЗДАН ПО ДЕЛУ. Между s2 и парящим всего
    // 2.4, между парящим и s3 — 5.3. Это не перекос: s2 и парящее НИГДЕ не
    // соприкасаются (парящий слой всегда окружён ореолом в цвет страницы), а
    // плитки лежат прямо НА панели, и их перепад к ней виден в каждом кадре.
    // Панель опущена с 15.94 до 13.99 намеренно: самое крупное сплошное пятно
    // экрана читалось светлой плашкой, а не поднятым слоем. Вместе с ней на 1.0
    // опущена s2 — иначе панель встала бы вровень с раскрытой карточкой.
    //
    // ПОТОЛКА ПО КОНТРАСТУ ЗДЕСЬ БОЛЬШЕ НЕТ. Прежняя лестница упиралась в порог
    // 4.5 тремя подписями разом (dim 5.34, акцент 4.58, красный 4.56). Уголь
    // темнее, и на самой светлой ступени (s3) худшая подпись теперь 5.27
    // (красный), dim 5.76, янтарь 7.21, акцент 7.89, fg 11.85.
    //
    // ── ЗЕЛЁНОГО КАК ОТДЕЛЬНОГО ЦВЕТА БОЛЬШЕ НЕТ ─────────────────────────────
    //
    // Акцент — мята. Прежний зелёный «работает» (#34E29E) от неё не отличим
    // глазом, а два разных смысла одним цветом — ровно та болезнь, которую тут
    // лечили: зелёная кнопка «Старт» горела, когда человек НЕ защищён. Токен
    // зелёного удалён, мята несёт обе роли, а различает их ФОРМА:
    //   • кнопка     = контур плюс подкраска (picked + рамка);
    //   • «работает» = залитая площадь (точка связи, значок в панели).
    // Оттого же «выключено» больше не красится акцентом: у неё свой цвет — dim.
    // Иначе кольцо панели горело бы мятой и при «выключен», и при «подключено».
    //
    // ── КРОМКИ: ИХ РОВНО ПЯТЬ, И БОЛЬШЕ НЕ БЫВАЕТ ────────────────────────────
    //
    // Это не запрет, а ИСЧЕРПЫВАЮЩИЙ СПИСОК: любая рамка в приложении — одна из
    // пяти (`hairline`, `hairlineFloat`, `edge`, `edgeSoft`, `edgeDone`), и
    // выбирать между «0.05», «0.07» и «0.08» больше не приходится. Раньше
    // приходилось: кромка невыбранного была написана в двадцати девяти местах
    // пятью разными числами, и три оболочки уже разошлись — в окне стояло
    // `#FFFFFF14` (0.0784) там, где здесь 0.08.
    //
    // `hairlineFloat` тише остальных намеренно: парящий блок и так поднят над
    // страницей заливкой, и яркая обводка отбирала бы у неё эту работу.
    // `edge(bright:)` — та же кромка выбранного, когда подниматься уже некуда
    // самой заливке: под курсором в окне, под пальцем на «Скопировать код».
    //
    // ── ВЫБРАННОЕ: ОДНО ПРАВИЛО НА ВСЁ ПРИЛОЖЕНИЕ ────────────────────────────
    //
    // ВЫБРАННОЕ = СВОЯ СТУПЕНЬ ПЛЮС ПОДКРАСКА, А НЕ ПОДКРАСКА ПОВЕРХ ФОНА
    // СТРАНИЦЫ. Прозрачность смешивается с тем, что лежит СЗАДИ, то есть с почти
    // чёрной страницей: выбранное выходило ТЕМНЕЕ невыбранного и читалось как
    // вдавленное.
    //
    // СТУПЕНЬ ЗДЕСЬ ОДНА — s1. Всякий выбираемый элемент (чип, переключатель,
    // кнопка лимита, недавняя сеть, кнопка) лежит НА СТРАНИЦЕ, а первая ступень
    // над страницей и есть s1. Ячейка нав-бара сидит на парящем слое, но
    // красится тем же цветом намеренно — иначе она спорила бы яркостью с
    // панелью состояния наверху экрана.
    //
    // СИЛУ ДЕРЖИТ УЖЕ НЕ КОНТРАСТ, А ЛЕСТНИЦА. На прежней палитре 0.15 упиралась
    // в подпись (4.57 при пороге 4.5); на угле подпись отпустила — красный
    // доходит до порога только к 0.26. Теперь силу задаёт другое: выбранное
    // должно встать НА ВЕРХНЮЮ СТУПЕНЬ, а не перепрыгнуть её. 0.14 даёт мяте
    // L* 19.54 при s3 = 19.31 — ровно вровень с плиткой. Подписи с запасом:
    // мята на своей подкраске 7.84, красный 5.64. `touched` (0.06) — для
    // крупных подкрашенных блоков: там полная сила утопила бы содержимое.
    //
    // ЦВЕТ — НЕ ЕДИНСТВЕННЫЙ ПРИЗНАК. Выбранное везде несёт ещё и рамку в
    // оттенке, и подпись со значком в нём же.
    // ── НАЧАЛО: значения из design/palette.toml (правит design/sync-palette.py) ──
    static let bg     = Color(hex: 0x08090B)      // s0 — страница
    static let card   = Color(hex: 0x15181D)      // s1 — карточка списка, поле ввода, кнопка «поделиться»
    static let cardHi = Color(hex: 0x1B1F25)      // s2 — раскрытая карточка, чип
    static let tile   = Color(hex: 0x2A2F39)      // s3 — плитка внутри панели или карточки
    static let float  = Color(hex: 0x232930)      // парящее: панель состояния и нав-бар
    static let accent = Color(hex: 0x2FE0A8)      // мята: и «это можно нажать», и «это работает»
    static let fg     = Color(hex: 0xEDF1F8)      // основной текст
    static let dim    = Color(hex: 0xA5AAB5)      // второстепенный текст и «выключено»
    static let red    = Color(hex: 0xFF7974)      // беда, которая сама не пройдёт
    static let amber  = Color(hex: 0xF5B14C)      // беда, которая пройдёт сама

    static let hairline = Color.white.opacity(0.08)
    static let hairlineFloat = Color.white.opacity(0.05)
    static func edge(_ tint: Color = accent, bright: Bool = false) -> Color { tint.opacity(bright ? 0.7 : 0.4) }
    static func edgeSoft(_ tint: Color = accent) -> Color { tint.opacity(0.28) }
    static func edgeDone(_ tint: Color = accent) -> Color { tint.opacity(0.5) }
    static func discFill(_ tint: Color) -> Color { tint.opacity(0.13) }
    static func discRing(_ tint: Color) -> Color { tint.opacity(0.3) }

    static func picked(_ tint: Color = accent) -> Color { mix(card, tint, 0.14) }
    static func touched(_ tint: Color = accent) -> Color { mix(card, tint, 0.06) }

    static let copiedMs: TimeInterval = 1.3
    // ── КОНЕЦ: значения из design/palette.toml ──

    /// Смешение в sRGB — байт-в-байт то же, что `mix` в Slint и в Android-теме.
    private static func mix(_ base: Color, _ tint: Color, _ k: CGFloat) -> Color {
        var br: CGFloat = 0, bgn: CGFloat = 0, bb: CGFloat = 0, a: CGFloat = 0
        var tr: CGFloat = 0, tgn: CGFloat = 0, tb: CGFloat = 0
        UIColor(base).getRed(&br, green: &bgn, blue: &bb, alpha: &a)
        UIColor(tint).getRed(&tr, green: &tgn, blue: &tb, alpha: &a)
        return Color(.sRGB,
                     red:   br  + (tr  - br)  * k,
                     green: bgn + (tgn - bgn) * k,
                     blue:  bb  + (tb  - bb)  * k,
                     opacity: 1)
    }
}

extension Color {
    init(hex: UInt32) {
        self.init(
            .sRGB,
            red:   Double((hex >> 16) & 0xFF) / 255,
            green: Double((hex >> 8) & 0xFF) / 255,
            blue:  Double(hex & 0xFF) / 255,
            opacity: 1
        )
    }
}
