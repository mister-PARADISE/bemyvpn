package org.bemyvpn

import androidx.compose.ui.graphics.Color

/** Палитра — та же, что в iOS-приложении (Theme.swift), тёмная тема. */
object Theme {
    // ── ЛЕСТНИЦА ПОВЕРХНОСТЕЙ: ЧЕТЫРЕ СТУПЕНИ, А НЕ ОДИННАДЦАТЬ ──
    //
    // Замер по снимкам давал одиннадцать разных подложек, и порядок в них был
    // нарушен: парящая панель оказывалась ТЕМНЕЕ карточки под ней — оттого и не
    // парила. Ступеней теперь ровно четыре, и каждая значит одно:
    // ЦВЕТНОСТЬ, А НЕ СЕРОСТЬ. Ступени были почти нейтрально-серыми
    // (насыщенность 26–30% при фоне в 29%), и рядом с фоном читались как грязь:
    // у страницы синева есть, у карточек — нет. Насыщенность поднята до 39–45%
    // при ТОЙ ЖЕ светлоте: контраст подписей зависит только от яркости, поэтому
    // цветность можно добавлять даром. Тон оставлен фоновый (220°).
    //
    // ШАГИ РАЗВЕДЕНЫ. Между s2 и float было 0.99 по CIE L* — глаз такой ступени
    // не видит, обе поверхности выглядели «никак». Теперь 3.6 / 2.3 / 2.3.
    //
    // ПОВЕРХНОСТИ ПОДНЯТЫ («грязные, мрачные» — про прежние). Вся лестница
    // сдвинута вверх на ~5 по L*: перепад блока к фону стал 11.6 / 15.2 / 17.5 /
    // 19.9 — блок теперь виден САМ, а не за счёт подпорок по краю.
    // Потолок держит подпись: dim на плитке = 5.34 при пороге 4.5, акцент 4.58,
    // красный 4.56. Выше поднимать нельзя — эти трое упрутся в порог.
    val bg      = Color(0xFF0B0E14)   // s0 — страница                            L* 3.9
    val card    = Color(0xFF172646)   // s1 — карточка списка, поле, «поделиться»  L* 15.5
    val cardHi  = Color(0xFF1E2E4E)   // s2 — раскрытая карточка, выбранное, чип   L* 19.1
    val tile    = Color(0xFF29385A)   // s3 — плитка внутри панели/карточки        L* 23.8
    val accent  = Color(0xFF08ABFF)
    val fg      = Color(0xFFEAECEF)
    // Поднят с #99A1B4: на посветлевшей плитке прежний давал 4.49 — ниже порога
    // 4.5. Это не вкус, а следствие подъёма поверхностей.
    val dim     = Color(0xFFA9B0BF)
    val green   = Color(0xFF34E29E)
    val red     = Color(0xFFFF7974)
    val amber   = Color(0xFFF5B14C)

    // ── ВЫБРАННОЕ: ОДНО ПРАВИЛО НА ВСЁ ПРИЛОЖЕНИЕ ────────────────────────────
    //
    // ВЫБРАННОЕ = СВОЯ СТУПЕНЬ ПЛЮС ПОДКРАСКА, А НЕ ПОДКРАСКА ПОВЕРХ ФОНА
    // СТРАНИЦЫ. Раньше чипы и переключатели красились полупрозрачным акцентом, а
    // прозрачность смешивается с тем, что лежит СЗАДИ — то есть с почти чёрной
    // страницей. При старой тёмной палитре это случайно давало L* 14.6 при
    // соседях 10.3 и 13.3, и выбранное выходило самым светлым. С палитрой
    // «Подъём» те же 0.15 дают 14.0 при соседях 15.5 (s1) и 19.1 (s2): выбранное
    // стало ТЕМНЕЕ невыбранного и читалось как вдавленное. Случайность
    // кончилась — правило поставлено явно.
    //
    // СТУПЕНЬ ЗДЕСЬ ОДНА — s1. Всякий выбираемый элемент (чип, переключатель,
    // кнопка лимита, недавняя сеть, кнопка) лежит НА СТРАНИЦЕ, а первая ступень
    // над страницей и есть s1. Поэтому «своя ступень плюс подкраска» сводится к
    // ОДНОМУ цвету, а функции остаётся лишь оттенок: синий у обычного действия,
    // красный у «Стоп». Ячейка нав-бара сидит на парящем слое, но красится тем
    // же цветом намеренно — см. ниже.
    //
    // СИЛА ПОДКРАСКИ УПЁРТА В КОНТРАСТ ПОДПИСИ, а не выбрана на глаз. Подпись на
    // выбранном — того же оттенка, что и подкраска, и чем светлее заливка, тем
    // ближе они друг к другу: 0.15 даёт 4.57 при пороге 4.5, а уже 0.16 — ровно
    // 4.50, без запаса. Отсюда потолок: выше поднимать нельзя, и именно поэтому
    // подкраску нельзя класть на s2 или на парящее (там та же 0.15 даёт 4.13 и
    // 3.88 — подпись за порогом). Заодно это решает и второе требование: ячейка
    // нав-бара выходит светлее своей панели всего на 2.4 по L* и не спорит с ней
    // яркостью.
    //
    // ЦВЕТ — НЕ ЕДИНСТВЕННЫЙ ПРИЗНАК. Выбранное везде несёт ещё и рамку в
    // оттенке, и подпись со значком в нём же: человеку с нарушением
    // цветовосприятия остаётся рамка, которой у невыбранного нет вовсе.

    /** Выбранное/включённое: ступень контрола (s1) плюс подкраска в полную силу. */
    fun picked(tint: Color = accent): Color = mix(tint, 0.15f)

    /**
     * Слабая подкраска: крупные подкрашенные блоки (раскрытая карточка, плашка
     * обновления) — там полная сила утопила бы собственное содержимое.
     */
    fun touched(tint: Color = accent): Color = mix(tint, 0.06f)

    // Смешение покомпонентно в sRGB — байт-в-байт то же, что `mix` в Slint и в
    // Theme.swift. Готовый `lerp` из Compose не годится: он с некоторых версий
    // интерполирует через Oklab, и три оболочки разъехались бы по цвету.
    private fun mix(tint: Color, k: Float) = Color(
        card.red + (tint.red - card.red) * k,
        card.green + (tint.green - card.green) * k,
        card.blue + (tint.blue - card.blue) * k,
    )
}
