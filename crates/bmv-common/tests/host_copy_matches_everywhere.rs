//! ЧАСОВОЙ ПРОТИВ РАЗЪЕХАВШИХСЯ СЛОВ: одна фраза вкладки «Хост» — один текст.
//!
//! Слова вкладки живут ЧЕТЫРЬМЯ отдельными копиями (разметка окна, Swift, Kotlin,
//! Rust терминала), потому что позвать `view.rs` из трёх из них сегодня нечем.
//! Копии уже расходились — и не по разу: то регистром, то многоточием, то целым
//! словом. Каждая по отдельности при этом компилируется и выглядит правильной на
//! своём экране, так что заметить расхождение можно только сравнив их рядом.
//!
//! Здесь и сравниваем: `PHRASES` — это ТЕКСТ, а список файлов при нём — те
//! оболочки, где он обязан лежать ДОСЛОВНО. Нет в одной — тест краснеет и
//! называет её поимённо.
//!
//! `{}` в тексте — место названия устройства: в окне «этот компьютер», на
//! Android «телефон», на iOS подстановка `\(Platform.device)`. Это ЗАКОННОЕ
//! отличие, и оно проверяется, а не игнорируется: на месте `{}` должно стоять
//! одно из имён `DEVICES` — любое другое слово оттуда часовой не пропустит.
//!
//! Приём одолжен у соседей (`one_place_per_rule.rs`, `palette_is_one_source.rs`):
//! дешевле поймать грепом, чем каждый раз ловить руками.

use std::path::{Path, PathBuf};

/// Корень репозитория. `CARGO_MANIFEST_DIR` = `<корень>/crates/bmv-common`.
fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap().parent().unwrap().to_path_buf()
}

// ── Четыре оболочки: по одному файлу на каждую ──────────────────────────────
const WINDOW: &str = "apps/bmv-gui/ui/host_page.slint";
const IOS: &str = "apps/ios/BeMyVPN/ContentView.swift";
const ANDROID: &str = "apps/android/app/src/main/java/org/bemyvpn/ui/HostTab.kt";
const TERMINAL: &str = "apps/bmv-cli/src/tui.rs";
/// Ошибки старта хоста лежат не в разметке, а там, где приходит ответ ядра.
const IOS_STATE: &str = "apps/ios/BeMyVPN/BeMyVPNApp.swift";
const ANDROID_STATE: &str = "apps/android/app/src/main/java/org/bemyvpn/AppState.kt";
const WINDOW_STATE: &str = "apps/bmv-gui/src/main.rs";

/// Чем оболочкам ЗАКОННО отличаться на месте `{}` — и только этим.
const DEVICES: &[&str] = &["этот компьютер", "телефон", "\\(Platform.device)"];

/// Фраза → оболочки, где она обязана лежать дословно.
type Phrase = (&'static str, &'static [&'static str]);
const PHRASES: &[Phrase] = &[
    // ── что вкладка вообще делает ──
    //
    // Здесь стояло «Раздайте свой интернет: … станет выходной точкой для
    // гостей» — тремя копиями и с неверным смыслом: у гостя интернет ЕСТЬ, ему
    // закрыли доступ. Он просит не мегабайтов, а чужую страну на выходе.
    (
        "Через ваш канал выйдет в сеть тот, кому закрыли доступ. \
         Для него {} станет выходом в интернет — сайты увидят вашу страну, а не его.",
        &[WINDOW, IOS, ANDROID],
    ),
    // Не «выходной точкой для друзей»: публичный хост берут из общего списка
    // чужие люди, а «выходная точка» — наше слово, не того, кто ею пользуется.
    ("Станьте чьим-то VPN", &[WINDOW, IOS, ANDROID]),
    // ── состояния хоста ──
    ("Раздаю", &[WINDOW, IOS, ANDROID, TERMINAL]),
    ("Раздача выключена", &[WINDOW, IOS, ANDROID, TERMINAL]),
    ("Запускаюсь…", &[WINDOW, IOS, ANDROID, TERMINAL]),
    ("Пробиваю канал наружу…", &[WINDOW, IOS, ANDROID]),
    ("Не удалось начать раздачу", &[WINDOW, IOS, ANDROID]),
    // ── подписи настроек ──
    ("Имя хоста (видно в каталоге)", &[WINDOW, IOS, ANDROID]),
    ("Лимит гостей", &[WINDOW, IOS, ANDROID, TERMINAL]),
    ("Пароль (пусто = без пароля)", &[WINDOW, IOS, ANDROID]),
    // ── пояснения к видимости: три ветки одного правила ──
    ("Виден всем в списке хостов — подключиться сможет любой.", &[WINDOW, IOS, ANDROID]),
    ("В списке не виден — подключиться можно только по коду выше.", &[WINDOW, IOS, ANDROID]),
    (
        "С паролем сеть всегда скрыта: публичная карточка выдала бы её \
         как раз тем, от кого вы закрылись. Подключение — по коду.",
        &[WINDOW, IOS, ANDROID],
    ),
    // ── ошибки старта: длинные фразы, четыре копии — самое место разойтись ──
    (
        "Не удалось определить ваш адрес в интернете — без него гости не найдут дорогу. \
         Попробуйте ещё раз, а если не проходит — из другой сети.",
        &[WINDOW_STATE, IOS_STATE, ANDROID_STATE, TERMINAL],
    ),
    ("Раздача не включилась — попробуйте ещё раз.", &[IOS_STATE, ANDROID_STATE]),
    // Сервер ответил, но кодом ответ не назвать. ДВЕ десктопные копии — телефоны
    // сюда не ходят: у них мост схлопывает такой случай в общий сентинел.
    // Фраза узкая: объяснённый отказ сервера показывается ЕГО словами, а не ею.
    ("Сервер не выдал код сети. Проверьте связь и попробуйте ещё раз.", &[WINDOW_STATE, TERMINAL]),
];

/// Комментарий ОБЪЯСНЯЕТ фразу и часто её же цитирует — по нему не сверяют.
///
/// Без этого часовой засчитывал бы за живой текст пояснение вида «иначе
/// „Раздача выключена“ и „Раздаю“ носили бы одну мяту»: копию можно было бы
/// стереть, а тест остался бы зелёным.
fn code_only(src: &str) -> String {
    src.lines()
        .filter(|l| {
            let t = l.trim_start();
            // `//` — все четыре языка; `/*`, `* `, `*/`, одинокая `*` — блочные
            // пояснения Kotlin и Swift. Именно `* ` со ПРОБЕЛОМ: строка кода
            // может начинаться со звёздочки разыменования.
            !(t.starts_with("//") || t.starts_with("/*") || t.starts_with("* ") || t.starts_with("*/") || t == "*")
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Есть ли фраза в тексте. `{}` принимает ровно имена устройств из `DEVICES`.
fn says(src: &str, phrase: &str) -> bool {
    let Some((head, tail)) = phrase.split_once("{}") else { return src.contains(phrase) };
    src.match_indices(head).any(|(i, _)| {
        let rest = &src[i + head.len()..];
        DEVICES.iter().any(|d| rest.strip_prefix(d).is_some_and(|r| r.starts_with(tail)))
    })
}

#[test]
fn one_phrase_reads_the_same_in_every_shell() {
    let root = repo_root();
    let mut guilty = Vec::new();

    for (phrase, shells) in PHRASES {
        assert!(shells.len() > 1, "фраза в одной оболочке сверять не с чем: «{phrase}»");
        for rel in *shells {
            let path = root.join(rel);
            let Ok(src) = std::fs::read_to_string(&path) else {
                guilty.push(format!("{rel}: файла нет — оболочка переехала, поправь путь в этом тесте"));
                continue;
            };
            if !says(&code_only(&src), phrase) {
                guilty.push(format!("{rel}:\n      нет фразы «{phrase}»"));
            }
        }
    }

    assert!(
        guilty.is_empty(),
        "слова вкладки «Хост» разъехались по оболочкам — на одном экране человек прочтёт одно, \
         на другом другое:\n  {}\n\
         Фраза живёт КОПИЯМИ (позвать view.rs из Swift, Kotlin и разметки окна сегодня нечем), \
         поэтому правят её сразу везде. Меняли формулировку нарочно — поменяйте её и в таблице \
         PHRASES этого теста, и в КАЖДОЙ перечисленной при ней оболочке.",
        guilty.join("\n  ")
    );
}
