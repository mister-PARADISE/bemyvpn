//! Справочник правил ПОКАЗА — один на все оболочки.
//!
//! ЧТО ЭТО. Чистые функции: данные на входе → готовый ответ на выходе. Модуль
//! ничем не владеет и ничего не помнит — ни состояния сеанса, ни таймеров, ни
//! сети, ни файлов, ни дескрипторов. Поэтому его можно звать откуда угодно, в
//! любом порядке и из любого потока, и поэтому же он НЕ трогает порядок закрытия
//! туннеля — на нём держатся прощание с хостом и честное «отключено».
//!
//! ЗАЧЕМ. Каждое правило отсюда раньше жило КОПИЯМИ в четырёх оболочках, и копии
//! молча разошлись: пустой протокол в окне подписывался «Обычный», а на телефоне
//! «Без шифра» — про хост, у которого шифр есть; часы сеанса в терминале
//! показывали «12 мин» и читались как зависшие; забитый хост в терминале давал
//! нажать «Подключить», хотя три другие оболочки кнопку гасили. Ничто при этом
//! не краснело — расхождение было невидимым. Рядом лежит грепалка
//! `tests/one_place_per_rule.rs`: она падает, если правило завелось вторым
//! местом, и сверяет пороги пинга с разметкой окна.
//!
//! ЧЕГО ЗДЕСЬ НЕ БУДЕТ. Ничего, что владеет системным ресурсом (туннель,
//! разрешения, окно, камера, фон) и ничего, что помнит между вызовами. Как
//! только такой слой начнёт хранить состояние и командовать туннелем, откатиться
//! будет нельзя — а пока он без памяти, любая оболочка вольна им не пользоваться.
//!
//! ИМЕНА ЗНАЧКОВ СЮДА НЕ ЕДУТ. Правило отдаёт СМЫСЛ (уровень защиты, уровень
//! тревоги), а картинку выбирает оболочка: у терминала это эмодзи, у окна —
//! векторный значок, у телефонов — свои наборы.

// ── Протокол ────────────────────────────────────────────────────────────────

/// Имя протокола по-человечески.
///
/// ПУСТАЯ СТРОКА — ЭТО «ОБЫЧНЫЙ», А НЕ «БЕЗ ШИФРА». Хост, не объявивший протокол
/// в каталоге, всё равно поднимает шифрованный канал (noise — умолчание ядра).
/// Раньше такой хост показывался как незашифрованный: человек видел «Без шифра»
/// там, где шифр есть, и та же самая запись каталога в терминале подписывалась
/// «Обычный» — две оболочки говорили противоположное об одном хосте.
///
/// Незнакомое имя показываем КАК ЕСТЬ. Врать «Без шифра» про неизвестный
/// протокол так же неверно, как врать про пустой: мы про него ничего не знаем.
pub fn proto_name(p: &str) -> &str {
    match p {
        "" | "noise" | "noise-aes" => "Обычный",
        "noise-obfs" => "Маскировка",
        "plain" => "Без шифра",
        other => other,
    }
}

/// Уровень защиты — то, что рисуется значком.
///
/// Отдаём именно уровень, а не имя картинки: наборы значков у оболочек разные
/// (эмодзи в терминале, `Icon*` в окне, SF Symbols на iOS, векторы на Android),
/// и общего имени у них нет. Кто рисует — тот и выбирает.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Protection {
    /// Защищено — обычный шифрованный канал.
    Encrypted,
    /// Замаскировано — то же шифрование плюс защита от DPI.
    Masked,
    /// Нет защиты — канал открытый, и это надо показывать.
    Plain,
    /// Неизвестно — протокол не из наших; врать про него нечего.
    Unknown,
}

/// Уровень защиты по имени протокола. Пустая строка — защищено (см. `proto_name`).
pub fn protection(p: &str) -> Protection {
    match p {
        "" | "noise" | "noise-aes" => Protection::Encrypted,
        "noise-obfs" => Protection::Masked,
        "plain" => Protection::Plain,
        _ => Protection::Unknown,
    }
}

// ── Часы сеанса ─────────────────────────────────────────────────────────────

/// Часы сеанса: `MM:SS`, после часа — `H:MM:SS`.
///
/// Именно ЧАСЫ, а не «12 мин». Округлённая до минут подпись стоит на месте
/// шестьдесят секунд подряд, и это читается как зависшая программа: человек
/// смотрит на неё как раз тогда, когда сомневается, работает ли VPN. Секунды
/// тикают — значит живо.
pub fn session_clock(sec: u64) -> String {
    let (h, m, s) = (sec / 3600, (sec % 3600) / 60, sec % 60);
    if h > 0 {
        format!("{h}:{m:02}:{s:02}")
    } else {
        format!("{m:02}:{s:02}")
    }
}

// ── Пинг ────────────────────────────────────────────────────────────────────

/// Отсюда пинг перестаёт быть «нормальным». Одна линейка на ВСЕ пинги — и до
/// хоста, и до координатора: раньше их было две, и меньшее число выходило
/// тревожнее большего (137 мс до хоста краснело, 162 мс до координатора
/// числилось хорошим).
pub const PING_AMBER_MS: u32 = 250;
/// Отсюда пинг плохой.
pub const PING_RED_MS: u32 = 500;

/// Подпись «не ответил». Короткий прочерк, а не фраза: место под него у всех
/// оболочек одинаково узкое, а смысл добирается приглушённым цветом и значком.
pub const PING_NO_ANSWER: &str = "—";

/// Насколько тревожна цифра. Цвет выбирает оболочка, порог — здесь.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Alarm {
    /// Норма МОЛЧИТ: обычный цвет текста, никакой похвалы.
    ///
    /// ЗЕЛЁНОГО В ПИНГЕ НЕТ ВОВСЕ: в этом приложении зелёный значит «работает»,
    /// а не «быстро», и зелёная цифра рядом с красной точкой обрыва врала бы.
    Calm,
    /// Янтарь — заметно, но жить можно.
    Amber,
    /// Красный — так пользоваться нельзя.
    Red,
    /// Приглушённо — ответа нет, тревожить нечем.
    Muted,
}

/// Пинг одним правилом: подпись и уровень тревоги вместе.
///
/// Вместе, потому что порознь они и разъезжались: подпись брали из одного места,
/// цвет считали в другом, и «нет ответа» оказывалось то приглушённым, то
/// обычным. `None` — хост не ответил; «ещё не мерили» оболочка показывает сама
/// (у неё для этого своя анимация ожидания).
pub fn ping(ms: Option<u32>) -> (String, Alarm) {
    match ms {
        None => (PING_NO_ANSWER.to_string(), Alarm::Muted),
        Some(v) if v < PING_AMBER_MS => (format!("{v} мс"), Alarm::Calm),
        Some(v) if v <= PING_RED_MS => (format!("{v} мс"), Alarm::Amber),
        Some(v) => (format!("{v} мс"), Alarm::Red),
    }
}

// ── Хост ────────────────────────────────────────────────────────────────────

/// Годен ли хост для подключения: живой и есть свободное место.
///
/// Терминал этого не спрашивал и давал нажать «Подключить» на забитом хосте —
/// попытка уходила в сеть и возвращалась отказом, а выглядело это как «программа
/// не работает». Три другие оболочки в тот же момент кнопку гасили.
///
/// `max_guests == 0` — хост не объявил потолок: мест не обещано, значит не годен.
pub fn host_usable(online: bool, guests: u32, max_guests: u32) -> bool {
    online && guests < max_guests
}

/// Как показывать хост: имя, а если имени нет — его код.
///
/// Пустая строка вместо имени оставляла в списке строку-призрак, по которой
/// нельзя опознать, к кому подключаешься.
pub fn host_display_name<'a>(name: &'a str, id: &'a str) -> &'a str {
    if name.is_empty() {
        id
    } else {
        name
    }
}

// ── Адрес координатора ──────────────────────────────────────────────────────

/// То, что набрал человек, → пригодный адрес координатора. Пусто → `None`.
///
/// Схему не показывают нигде, значит и набирать её человек не станет —
/// «bemyvpn.net» обязано работать. Голому имени приписываем `https`:
/// незашифрованную схему нужно указать явно, случайно на неё свалиться нельзя.
///
/// Схему отделяем ДО обрезки хвостовых слэшей: иначе одинокое «https://»
/// (человек стёр адрес, оставив схему) превращалось в «https:» и получало ВТОРУЮ
/// схему спереди — «https://https:», и приложение честно уходило искать
/// координатор по этому адресу.
///
/// `None` — это ОТКАЗ, о котором оболочка обязана сказать вслух. Телефоны на том
/// же вводе молча выходили из настройки: кнопка нажата, ничего не сохранено,
/// ничего не сказано.
pub fn coordinator_url(input: &str) -> Option<String> {
    let t = input.trim();
    let (scheme, rest) = match (t.strip_prefix("https://"), t.strip_prefix("http://")) {
        (Some(r), _) => ("https://", r),
        (_, Some(r)) => ("http://", r),
        _ => ("https://", t),
    };
    let rest = rest.trim_end_matches('/');
    (!rest.is_empty()).then(|| format!("{scheme}{rest}"))
}

/// Адрес ДЛЯ ПОКАЗА — без схемы и без хвостового слэша.
///
/// Соединение у нас всегда https, поэтому «https://» перед каждым адресом
/// занимает место и ничего не сообщает. Хранение и запросы схему сохраняют —
/// срезается она только на экране.
pub fn without_scheme(url: &str) -> String {
    url.trim()
        .trim_start_matches("https://")
        .trim_start_matches("http://")
        .trim_end_matches('/')
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Хост, не назвавший протокол, не смеет числиться незашифрованным.
    #[test]
    fn a_host_that_did_not_name_its_protocol_is_not_called_unencrypted() {
        assert_eq!(proto_name(""), "Обычный");
        assert_eq!(proto_name("noise"), "Обычный");
        assert_eq!(proto_name("noise-aes"), "Обычный");
        assert_eq!(proto_name("noise-obfs"), "Маскировка");
        // «Без шифра» остаётся ровно за тем протоколом, который и правда без шифра.
        assert_eq!(proto_name("plain"), "Без шифра");
        // Незнакомое — как есть, без выдумок в любую сторону.
        assert_eq!(proto_name("wireguard"), "wireguard");
    }

    /// Значок идёт за подписью: где сказано «шифр есть», там и щит.
    #[test]
    fn the_badge_never_contradicts_the_caption() {
        assert_eq!(protection(""), Protection::Encrypted);
        assert_eq!(protection("noise"), Protection::Encrypted);
        assert_eq!(protection("noise-aes"), Protection::Encrypted);
        assert_eq!(protection("noise-obfs"), Protection::Masked);
        assert_eq!(protection("plain"), Protection::Plain);
        assert_eq!(protection("wireguard"), Protection::Unknown);
        for p in ["", "noise", "noise-aes", "noise-obfs", "plain", "wireguard"] {
            let no_shield = protection(p) == Protection::Plain;
            assert_eq!(
                no_shield,
                proto_name(p) == "Без шифра",
                "подпись и значок разошлись на протоколе {p:?}"
            );
        }
    }

    /// Часы обязаны тикать: минутная подпись выглядит зависшей.
    #[test]
    fn session_clock_reads_like_a_clock() {
        assert_eq!(session_clock(0), "00:00");
        assert_eq!(session_clock(9), "00:09");
        assert_eq!(session_clock(75), "01:15");
        assert_eq!(session_clock(3599), "59:59");
        assert_eq!(session_clock(3600), "1:00:00");
        assert_eq!(session_clock(3661), "1:01:01");
        assert_eq!(session_clock(36000), "10:00:00");
        // Секунды видны на КАЖДОЙ отметке — иначе подпись стоит по минуте.
        assert_ne!(session_clock(61), session_clock(62));
    }

    /// Пороги пинга и то, что зелёного в нём нет.
    #[test]
    fn ping_is_calm_until_it_is_not() {
        assert_eq!(ping(Some(0)), ("0 мс".into(), Alarm::Calm));
        assert_eq!(ping(Some(249)), ("249 мс".into(), Alarm::Calm));
        assert_eq!(ping(Some(250)).1, Alarm::Amber);
        assert_eq!(ping(Some(500)).1, Alarm::Amber);
        assert_eq!(ping(Some(501)).1, Alarm::Red);
        assert_eq!(ping(None), (PING_NO_ANSWER.to_string(), Alarm::Muted));
        // Порядок порогов — на случай правки констант «на глаз».
        const { assert!(PING_AMBER_MS < PING_RED_MS) };
    }

    /// Забитый и мёртвый хост не годятся — на них и кнопка гаснет.
    #[test]
    fn a_full_host_is_not_offered() {
        assert!(host_usable(true, 0, 8));
        assert!(host_usable(true, 7, 8));
        assert!(!host_usable(true, 8, 8), "мест нет — подключаться некуда");
        assert!(!host_usable(true, 9, 8), "переполнен — тем более");
        assert!(!host_usable(false, 0, 8), "офлайн — не годен даже пустой");
        assert!(!host_usable(true, 0, 0), "потолок не объявлен — мест не обещано");
    }

    /// Безымянный хост опознаётся по коду, а не пустотой.
    #[test]
    fn a_nameless_host_shows_its_code() {
        assert_eq!(host_display_name("Домашний", "AB12CD34"), "Домашний");
        assert_eq!(host_display_name("", "AB12CD34"), "AB12CD34");
        assert!(!host_display_name("", "AB12CD34").is_empty());
    }

    /// Адрес координатора можно набрать без схемы, и отказ обязан быть заметным.
    #[test]
    fn a_coordinator_address_does_not_need_its_scheme_typed_by_hand() {
        assert_eq!(coordinator_url("bemyvpn.net").as_deref(), Some("https://bemyvpn.net"));
        assert_eq!(coordinator_url("  bemyvpn.net/ ").as_deref(), Some("https://bemyvpn.net"));
        // Явную схему не трогаем — в том числе незашифрованную: на неё нужно
        // сваливаться осознанно, а не молча.
        assert_eq!(coordinator_url("http://10.0.0.5:3330").as_deref(), Some("http://10.0.0.5:3330"));
        assert_eq!(coordinator_url("https://свой.сервер").as_deref(), Some("https://свой.сервер"));
        // А вот из ничего адреса не бывает — и это ОТКАЗ, а не тихий пропуск.
        assert!(coordinator_url("").is_none());
        assert!(coordinator_url("   ").is_none());
        assert!(coordinator_url("https://").is_none(), "схема без адреса — не адрес");
        assert!(coordinator_url("http://").is_none());
    }

    /// Показ и работа: с экрана схема уходит, из адреса — нет.
    #[test]
    fn the_address_loses_its_scheme_on_screen_but_keeps_it_in_use() {
        assert_eq!(without_scheme("https://bemyvpn.net"), "bemyvpn.net");
        assert_eq!(without_scheme("http://10.0.0.5:3330"), "10.0.0.5:3330");
        assert_eq!(without_scheme("https://bemyvpn.net/"), "bemyvpn.net");
        // Показанное обязано вернуться в тот же рабочий адрес.
        for full in ["https://bemyvpn.net", "https://свой.сервер:8443"] {
            assert_eq!(coordinator_url(&without_scheme(full)).as_deref(), Some(full));
        }
    }
}
