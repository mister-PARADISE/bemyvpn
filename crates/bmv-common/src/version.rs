//! Версия сборки и сравнение версий — общее для всех оболочек.
//!
//! Версия берётся из тега релиза (env `BMV_VERSION`, CI отдаёт «1.6» из «v1.6»),
//! а НЕ из `Cargo.toml`: там стоит `1.0.0` и с тегами он давно разошёлся —
//! держать два источника правды значит рано или поздно соврать пользователю.
//! Тот же приём уже используется для Android (`build.gradle`), так что способ
//! в проекте один, а не два.
//!
//! Локальная сборка без переменной получает `0.0-dev` — видно, что это не
//! релиз, и такая сборка не выдаёт себя за свежую при проверке обновлений.

/// Версия текущей сборки: «1.6» для релиза, «0.0-dev» для локальной.
pub const VERSION: &str = match option_env!("BMV_VERSION") {
    Some(v) if !v.is_empty() => v,
    _ => "0.0-dev",
};

/// Это сборка из тега (а не локальная)? Локальные не предлагаем обновлять:
/// разработчик собрал сам, подсовывать ему релиз поверх — вредно.
pub fn is_release_build() -> bool {
    VERSION != "0.0-dev"
}

/// Разобрать версию в числа для сравнения. «1.6» → [1, 6, 0].
/// Хвост после первого не-цифрового символа отбрасывается («1.6-rc2» → [1,6,0]).
fn parts(v: &str) -> [u64; 3] {
    let mut out = [0u64; 3];
    for (i, p) in v.trim_start_matches('v').split('.').take(3).enumerate() {
        let digits: String = p.chars().take_while(|c| c.is_ascii_digit()).collect();
        out[i] = digits.parse().unwrap_or(0);
    }
    out
}

/// Новее ли `candidate`, чем `current`.
///
/// Сравнение ПО ЧИСЛАМ, а не по строкам: строкой «1.10» оказалась бы МЕНЬШЕ
/// «1.9», и пользователь никогда не увидел бы обновление после девятого выпуска.
pub fn is_newer(candidate: &str, current: &str) -> bool {
    parts(candidate) > parts(current)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numeric_compare_not_lexicographic() {
        // Главный случай, ради которого сравнение числовое: строкой "1.10" < "1.9".
        assert!(is_newer("1.10", "1.9"), "1.10 должна быть новее 1.9");
        assert!(!is_newer("1.9", "1.10"));

        assert!(is_newer("2.0", "1.99"));
        assert!(is_newer("1.6", "1.5"));
        assert!(!is_newer("1.5", "1.5"), "та же версия — не обновление");
        assert!(!is_newer("1.4", "1.5"), "старее — не обновление");

        // Разная длина и мусор в хвосте не должны ломать разбор.
        assert!(is_newer("1.6.1", "1.6"));
        assert!(!is_newer("1.6", "1.6.1"));
        assert!(is_newer("v1.6", "1.5"), "префикс v допустим");
        assert!(!is_newer("1.6-rc1", "1.6"), "суффикс отбрасывается, версии равны");

        // Локальная сборка старее любого релиза — но обновлять её мы не будем
        // (is_release_build), это лишь проверка самого сравнения.
        assert!(is_newer("1.0", "0.0-dev"));
    }
}
