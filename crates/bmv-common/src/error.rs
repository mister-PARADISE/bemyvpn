//! Единый тип ошибки проекта. Слои возвращают `bmv_common::Result<T>`.
//!
//! ТЕКСТ ОШИБКИ ЧИТАЕТ ЧЕЛОВЕК — тот же самый, что стоит в заголовке окна и в
//! строке терминала. Поэтому в `Display` больше нет категорий («знакомство/
//! сигналинг: », «сеть/NAT: », «протокол: »): человеку они не объясняли ничего,
//! а стояли первыми — и первым словом ошибки был жаргон. Разбирать ошибку по
//! роду надо по ВАРИАНТУ, а не по префиксу текста.

use thiserror::Error;

#[derive(Debug, Error)]
pub enum Error {
    #[error("{0}")]
    Io(#[from] std::io::Error),

    #[error("{0}")]
    Config(String),

    #[error("{0}")]
    Protocol(String),

    #[error("{0}")]
    Signal(String),

    #[error("{0}")]
    Net(String),

    /// Сервер ОТКАЗАЛ: `reason` — готовый текст для человека, `code` — причина
    /// в машинном виде (422 — снаружи до вас не достучаться, 403 — код не наш).
    ///
    /// Код обязан ехать ОТДЕЛЬНЫМ полем. Раньше он терялся ещё в `bmv-signal`
    /// (брали только `reason`), а все четыре оболочки искали его подстрокой в
    /// тексте — `contains("422")`. То есть не находили никогда: вместо
    /// объяснения человек читал сырую строку сервера, а протухшая подпись кода
    /// не лечилась сама, хотя весь код для этого написан.
    #[error("{reason}")]
    Refused { code: u16, reason: String },

    #[error("{0}")]
    Other(String),
}

pub type Result<T> = std::result::Result<T, Error>;

impl Error {
    pub fn other(msg: impl Into<String>) -> Self {
        Error::Other(msg.into())
    }

    /// Код отказа сервера, если отказал именно он. Оболочкам — чтобы решать по
    /// причине, а не по буквам в тексте.
    pub fn refusal_code(&self) -> Option<u16> {
        match self {
            Error::Refused { code, .. } => Some(*code),
            _ => None,
        }
    }
}
