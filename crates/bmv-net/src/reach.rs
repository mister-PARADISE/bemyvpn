//! КУДА ВЕДЁТ АДРЕС — одна таблица диапазонов на все вопросы о чужом адресе.
//!
//! Вопросов правда несколько, и ответы у них РАЗНЫЕ — потому здесь категории, а
//! не «можно/нельзя»:
//!
//!   * `public_only` — сюда хост открывает НАСТОЯЩИЙ сокет по адресу, который
//!     назвал гость (адрес назначения — это его IP-пакеты). Только интернет:
//!     иначе гость чужими руками ходит по внутренней сети хозяина — метаданные
//!     облака `169.254.169.254` (кража ключей!), локальные админки, роутер.
//!   * `punch_target_allowed` — куда шлём встречный PUNCH. Адреса пира приходят
//!     С ЕГО СЛОВ (через координатор), и по каждому уходят десятки пачек UDP:
//!     без фильтра это сканер чужой LAN, оплаченный чужой машиной. Но пир в ТОЙ
//!     ЖЕ локальной сети — рабочий случай, поэтому LAN тут разрешена.
//!   * `plausible_external` — что мы готовы считать СВОИМ внешним адресом. Ответ
//!     STUN приходит по UDP от чужой машины (подделывается кем угодно, кто угадал
//!     наш порт), а названный адрес уезжает в каталог, и все гости пойдут
//!     пробивать NAT именно туда.
//!
//! ПОЧЕМУ ВМЕСТЕ. Таблица диапазонов была записана ДВАЖДЫ — в SSRF-фильтре хоста
//! (`bmv-tunnel`) и здесь, в разборе STUN, — и уже разошлась молча: site-local
//! `fec0::/10` и IPv4, зашитый в IPv6, знала только первая. Новый запрещённый
//! диапазон пришлось бы дописывать в оба места, а пропустить одно — бесшумно.
//! Теперь диапазоны в одном месте, а каждая политика — одна строка, из которой
//! ВИДНО, чем она отличается от соседней. Сторож против третьей копии —
//! `tests/one_table_of_ranges.rs`.
//!
//! Координатор (`server/coordinator`) держит свою копию сознательно: он
//! самодостаточный крейт и не тянет `bmv-*` (см. его Cargo.toml).

use std::net::{IpAddr, Ipv4Addr, Ipv6Addr, SocketAddr};

/// Куда ведёт адрес.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Reach {
    /// Обычный интернет — единственное, куда хост открывает сокет.
    Public,
    /// Чья-то локальная сеть: 10/8, 172.16/12, 192.168/16, ULA `fc00::/7`.
    Lan,
    /// Общий NAT оператора (`100.64/10`): не интернет и не LAN — так выходит
    /// обычный мобильный.
    Carrier,
    /// Служебное и снаружи недостижимое: петля, link-local (в том числе
    /// `169.254.169.254` — метаданные облака), site-local `fec0::/10`,
    /// мультикаст, бродкаст, `0.0.0.0/8`, документационные и `240/4`.
    Internal,
}

/// Классифицировать адрес. IPv4, ЗАШИТЫЙ в IPv6, судим по правилам IPv4 —
/// иначе любой фильтр обходится тем, что тот же адрес записан иначе
/// (см. `embedded_v4`).
fn reach(ip: IpAddr) -> Reach {
    match ip {
        IpAddr::V4(a) => {
            let o = a.octets();
            // Служебное проверяем ПЕРВЫМ: ошибка в порядке должна ронять в
            // сторону запрета, а не разрешения.
            if a.is_loopback()
                || a.is_link_local() // 169.254/16, в т.ч. метаданные облака
                || a.is_unspecified()
                || a.is_broadcast()
                || a.is_multicast()
                || a.is_documentation()
                || o[0] == 0 // 0/8
                || o[0] >= 240
            {
                Reach::Internal
            } else if a.is_private() {
                Reach::Lan
            } else if o[0] == 100 && (o[1] & 0xC0) == 64 {
                Reach::Carrier
            } else {
                Reach::Public
            }
        }
        IpAddr::V6(a) => {
            if let Some(v4) = embedded_v4(a) {
                return reach(v4.into());
            }
            let s0 = a.segments()[0];
            if a.is_loopback()
                || a.is_unspecified()
                || a.is_multicast()
                || (s0 & 0xffc0) == 0xfe80 // link-local fe80::/10
                || (s0 & 0xffc0) == 0xfec0 // site-local fec0::/10: из стандарта
            // убран, но стеки его понимают, и в старых корпоративных сетях он живой
            {
                Reach::Internal
            } else if (s0 & 0xfe00) == 0xfc00 {
                Reach::Lan // ULA fc00::/7
            } else {
                Reach::Public
            }
        }
    }
}

/// Вытащить IPv4, зашитый в IPv6-адрес, если он там есть.
///
/// Три способа записать «тот же самый» адрес, каждый из которых обходил бы
/// проверку по IPv4-диапазонам, если смотреть только на внешнюю форму:
///   * `::ffff:a.b.c.d`  — v4-mapped, ядро идёт прямо по IPv4;
///   * `64:ff9b::a.b.c.d` — NAT64 (RFC 6052), шлюз переводит в IPv4-пакет;
///   * `2002:AABB:CCDD::/48` — 6to4 (RFC 3056), адрес шлюза в следующих 32 битах.
fn embedded_v4(a: Ipv6Addr) -> Option<Ipv4Addr> {
    if let Some(v4) = a.to_ipv4_mapped() {
        return Some(v4);
    }
    let s = a.segments();
    // NAT64 well-known prefix 64:ff9b::/96 — адрес в последних двух группах.
    if s[0] == 0x0064 && s[1] == 0xff9b && s[2] == 0 && s[3] == 0 && s[4] == 0 && s[5] == 0 {
        return Some(Ipv4Addr::from(((s[6] as u32) << 16) | s[7] as u32));
    }
    // 6to4 2002::/16 — адрес шлюза в группах 1 и 2.
    if s[0] == 0x2002 {
        return Some(Ipv4Addr::from(((s[1] as u32) << 16) | s[2] as u32));
    }
    None
}

/// SSRF-ЗАЩИТА ХОСТА: открывать сокет можно ТОЛЬКО в обычный интернет.
///
/// Порт не смотрим сознательно: подключиться к нулевому порту всё равно нельзя,
/// а решение о диапазоне от порта не зависит.
pub fn public_only(dst: &SocketAddr) -> bool {
    reach(dst.ip()) == Reach::Public
}

/// КУДА МОЖНО СЛАТЬ ВСТРЕЧНЫЙ PUNCH: всё, кроме служебного.
///
/// Разница с `public_only` ровно одна и она видна здесь: пир в локальной сети
/// (или за общим NAT оператора) — законная точка входа, и резать её нельзя,
/// иначе гость из той же квартиры перестанет подключаться.
pub fn punch_target_allowed(dst: &SocketAddr) -> bool {
    dst.port() != 0 && reach(dst.ip()) != Reach::Internal
}

/// МОЖЕТ ЛИ ЭТО БЫТЬ НАШИМ ВНЕШНИМ АДРЕСОМ (ответ STUN).
///
/// Чужая LAN отвергается без потерь: если внешний адрес совпал с локальным, он и
/// так уже анонсирован кандидатом `local_ip()`. А вот адрес общего NAT оператора
/// принимаем: у мобильного он и есть «внешний», какой видно.
pub fn plausible_external(addr: &SocketAddr) -> bool {
    addr.port() != 0 && matches!(reach(addr.ip()), Reach::Public | Reach::Carrier)
}

// ── Обходные пути фильтра ─────────────────────────────────────────────────────
//
// Гость сам пишет адрес назначения в своих IP-пакетах, а адреса пира приходят с
// его слов. Фильтр обязан резать всё внутреннее — а способов записать внутренний
// адрес так, чтобы он не выглядел внутренним, придумано много. Каждый тест
// ниже — отдельный приём.
#[cfg(test)]
mod tests {
    use super::*;

    fn a(s: &str) -> SocketAddr {
        s.parse().unwrap()
    }

    #[test]
    fn ssrf_blocks_internal_allows_public() {
        // Публичный интернет — можно.
        assert!(public_only(&a("8.8.8.8:443")));
        assert!(public_only(&a("1.1.1.1:53")));
        // Внутреннее/опасное — нельзя.
        assert!(!public_only(&a("127.0.0.1:8080"))); // локальные сервисы
        assert!(!public_only(&a("169.254.169.254:80"))); // cloud metadata!
        assert!(!public_only(&a("10.0.0.5:22"))); // LAN
        assert!(!public_only(&a("192.168.1.1:80"))); // роутер
        assert!(!public_only(&a("172.16.4.4:445"))); // LAN
        assert!(!public_only(&a("100.64.0.1:80"))); // CGNAT
        assert!(!public_only(&a("0.0.0.0:80")));
        assert!(!public_only(&a("[::1]:80"))); // v6 петля
        assert!(!public_only(&a("[fe80::1]:80"))); // v6 link-local
        assert!(!public_only(&a("[fc00::1]:80"))); // v6 ULA
        assert!(!public_only(&a("[::ffff:10.0.0.1]:80"))); // v4-mapped приватка
    }

    /// v4-mapped v6 (`::ffff:a.b.c.d`) — тот же адрес, записанный по-другому.
    /// Классика обхода: проверка «это же IPv6» пропускает, а ядро идёт по IPv4.
    #[test]
    fn ssrf_v4_mapped_covers_every_internal_range() {
        for s in [
            "[::ffff:127.0.0.1]:22",       // петля
            "[::ffff:169.254.169.254]:80", // метаданные облака
            "[::ffff:10.0.0.5]:22",
            "[::ffff:192.168.1.1]:80",
            "[::ffff:172.16.0.1]:445",
            "[::ffff:100.64.0.1]:80", // CGNAT
            "[::ffff:0.0.0.0]:80",
        ] {
            assert!(!public_only(&a(s)), "v4-mapped обход пролез: {s}");
        }
        // …и при этом обычный публичный адрес в той же записи проходить обязан.
        assert!(public_only(&a("[::ffff:8.8.8.8]:53")));
    }

    /// Устаревший site-local IPv6 `fec0::/10`. Из стандарта его убрали, но стеки
    /// его понимают, и в старых корпоративных сетях он живой — то есть это
    /// рабочий адрес внутренней сети, который наш фильтр обязан резать.
    #[test]
    fn ssrf_blocks_ipv6_site_local() {
        assert!(!public_only(&a("[fec0::1]:80")), "site-local fec0::/10 пролез");
        assert!(!public_only(&a("[feff::1]:80")), "верхняя граница fec0::/10 пролезла");
    }

    /// NAT64 `64:ff9b::/96`: адрес несёт в себе IPv4 в младших 32 битах, и шлюз
    /// NAT64 переведёт его в настоящий IPv4-пакет. То есть `64:ff9b::7f00:1`
    /// в сети с NAT64 — это 127.0.0.1.
    #[test]
    fn ssrf_blocks_nat64_embedded_internal_v4() {
        assert!(!public_only(&a("[64:ff9b::7f00:1]:22")), "NAT64 к петле пролез");
        assert!(!public_only(&a("[64:ff9b::a9fe:a9fe]:80")), "NAT64 к метаданным пролез");
        assert!(!public_only(&a("[64:ff9b::c0a8:101]:80")), "NAT64 к роутеру пролез");
    }

    /// 6to4 `2002::/16`: следующие 32 бита — IPv4-адрес шлюза. На хосте с 6to4
    /// это ещё один способ записать внутренний адрес.
    #[test]
    fn ssrf_blocks_6to4_embedded_internal_v4() {
        assert!(!public_only(&a("[2002:7f00:1::1]:22")), "6to4 к 127.0.0.1 пролез");
        assert!(!public_only(&a("[2002:c0a8:101::1]:80")), "6to4 к 192.168.1.1 пролез");
        // Обычный 6to4 в публичный адрес запрещать не за что.
        assert!(public_only(&a("[2002:808:808::1]:80")), "6to4 к 8.8.8.8 зря отклонён");
    }

    /// Границы приватных диапазонов: соседние адреса СНАРУЖИ блока обязаны
    /// проходить, иначе фильтр отрезает кусок настоящего интернета.
    #[test]
    fn ssrf_boundaries_are_exact() {
        // 172.16/12 — ровно 172.16.0.0 … 172.31.255.255.
        assert!(!public_only(&a("172.16.0.0:80")));
        assert!(!public_only(&a("172.31.255.255:80")));
        assert!(public_only(&a("172.15.255.255:80")), "172.15.x — публичный, зря отрезан");
        assert!(public_only(&a("172.32.0.0:80")), "172.32.x — публичный, зря отрезан");
        // 100.64/10 (CGNAT) — 100.64.0.0 … 100.127.255.255.
        assert!(!public_only(&a("100.127.255.255:80")));
        assert!(public_only(&a("100.63.255.255:80")), "100.63.x — публичный, зря отрезан");
        assert!(public_only(&a("100.128.0.0:80")), "100.128.x — публичный, зря отрезан");
        // 240/4 зарезервирован, 239.x — мультикаст (тоже нельзя), 223.x — можно.
        assert!(!public_only(&a("240.0.0.1:80")));
        assert!(public_only(&a("223.255.255.255:80")), "223.x — публичный, зря отрезан");
    }

    /// Лазейка «сам себе прокси» на ОДНУ строку ниже по стеку: порт 0.
    /// Подключиться к нему нельзя, но проверить, что фильтр не падает и не
    /// пропускает внутренний адрес из-за нулевого порта, стоит.
    #[test]
    fn ssrf_zero_port_does_not_bypass() {
        assert!(!public_only(&a("127.0.0.1:0")));
        assert!(!public_only(&a("[::1]:0")));
        assert!(!public_only(&a("[::ffff:10.0.0.1]:0")));
    }

    /// ЦЕЛИ ВСТРЕЧНОГО ПРОБИТИЯ. Адреса ждущего гостя приходят хосту С ЕГО СЛОВ
    /// (через координатор), и хост шлёт туда 48 пачек UDP с шагом 250мс. Без
    /// фильтра это сканер чужой LAN и облачных метаданных, оплаченный чужой
    /// машиной. При этом гость в ТОЙ ЖЕ локальной сети — рабочий сценарий (потому
    /// в кандидатах и есть local_ip), и приватку резать нельзя.
    #[test]
    fn punch_targets_exclude_internal_but_keep_lan() {
        use super::punch_target_allowed as ok;
        // Свой же хост, чужие админки, метаданные облака, мультикаст — нельзя.
        assert!(!ok(&a("127.0.0.1:40000")), "петля");
        assert!(!ok(&a("169.254.169.254:80")), "метаданные облака");
        assert!(!ok(&a("169.254.1.1:40000")), "link-local");
        assert!(!ok(&a("224.0.0.1:40000")), "мультикаст");
        assert!(!ok(&a("255.255.255.255:40000")), "бродкаст");
        assert!(!ok(&a("0.0.0.0:40000")));
        assert!(!ok(&a("240.0.0.1:40000")), "зарезервированный 240/4");
        assert!(!ok(&a("8.8.8.8:0")), "нулевой порт — пробивать некуда");
        assert!(!ok(&a("[::1]:40000")), "v6 петля");
        assert!(!ok(&a("[fe80::1]:40000")), "v6 link-local");
        assert!(!ok(&a("[fec0::1]:40000")), "v6 site-local");
        assert!(!ok(&a("[::ffff:127.0.0.1]:40000")), "петля в записи v4-mapped");
        assert!(!ok(&a("[64:ff9b::a9fe:a9fe]:80")), "метаданные через NAT64");
        // Публичный интернет и ЛОКАЛЬНАЯ СЕТЬ — можно (иначе гость из той же
        // квартиры/офиса перестал бы подключаться).
        assert!(ok(&a("45.11.22.33:40000")), "публичный адрес зря отрезан");
        assert!(ok(&a("192.168.1.5:40000")), "гость в той же LAN — рабочий случай");
        assert!(ok(&a("10.1.2.3:40000")), "LAN 10/8 зря отрезана");
        assert!(ok(&a("172.16.5.5:40000")), "LAN 172.16/12 зря отрезана");
        assert!(ok(&a("100.64.0.1:40000")), "CGNAT — обычный мобильный гость");
        assert!(ok(&a("[fc00::1]:40000")), "ULA — та же LAN по IPv6");
    }

    /// ЧЕМ ТРИ ПОЛИТИКИ ОТЛИЧАЮТСЯ ДРУГ ОТ ДРУГА. Пока таблица была записана
    /// дважды, разницу приходилось вычитывать глазами, сличая два двенадцатистрочных
    /// блока; здесь она перечислена явно, и сдвиг любой из политик к соседке
    /// (например «пустим PUNCH только в интернет» или «примем LAN за свой внешний
    /// адрес») ломает ровно эту строку.
    #[test]
    fn the_three_policies_differ_exactly_here() {
        // Чужая LAN: сокет — нельзя, PUNCH — можно (пир в той же квартире),
        // своим внешним адресом не бывает (его анонсирует local_ip).
        let lan = a("192.168.1.5:40000");
        assert!(!public_only(&lan));
        assert!(punch_target_allowed(&lan));
        assert!(!plausible_external(&lan));

        // Общий NAT оператора: сокет — нельзя (это чужая внутренняя сеть),
        // PUNCH — можно, и «внешним» для мобильного он как раз бывает.
        let cgnat = a("100.64.0.1:40000");
        assert!(!public_only(&cgnat));
        assert!(punch_target_allowed(&cgnat));
        assert!(plausible_external(&cgnat));

        // Интернет — да во всех трёх смыслах.
        let pub_ = a("45.11.22.33:40000");
        assert!(public_only(&pub_) && punch_target_allowed(&pub_) && plausible_external(&pub_));

        // Служебное — нет ни в одном.
        for s in ["127.0.0.1:80", "169.254.169.254:80", "224.0.0.1:80", "240.0.0.1:80"] {
            let d = a(s);
            assert!(!public_only(&d) && !punch_target_allowed(&d) && !plausible_external(&d), "{s}");
        }

        // Нулевой порт: адресом назначения он не бывает (туда просто не
        // подключиться), а вот пробивать и анонсировать — некуда.
        assert!(!punch_target_allowed(&a("45.11.22.33:0")));
        assert!(!plausible_external(&a("45.11.22.33:0")));
    }

    /// Разбор вложенного IPv4 — отдельно от политики: если он ошибётся, фильтр
    /// начнёт судить не тот адрес, и это не заметит ни один тест выше.
    #[test]
    fn embedded_v4_extracts_exactly_the_right_address() {
        let v6 = |s: &str| s.parse::<Ipv6Addr>().unwrap();
        assert_eq!(embedded_v4(v6("::ffff:1.2.3.4")), Some(Ipv4Addr::new(1, 2, 3, 4)));
        assert_eq!(embedded_v4(v6("64:ff9b::102:304")), Some(Ipv4Addr::new(1, 2, 3, 4)));
        assert_eq!(embedded_v4(v6("2002:102:304::1")), Some(Ipv4Addr::new(1, 2, 3, 4)));
        // Похожие, но НЕ несущие адрес: не выдумываем IPv4 там, где его нет.
        assert_eq!(embedded_v4(v6("64:ff9b:1::102:304")), None, "не well-known NAT64-префикс");
        assert_eq!(embedded_v4(v6("2003:102:304::1")), None, "не 6to4");
        assert_eq!(embedded_v4(v6("2001:db8::1")), None);
    }
}
